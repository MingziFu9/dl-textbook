def main():
    terms = g.parse()
    nodes, names = [], set()
    for ch, rows in terms.items():
        for term, aid, d in rows:
            nodes.append({"id": term, "ch": ch, "cat": CAT_FIX.get(term, CAT_OF_CH[ch]), "a": aid, "d": d})
            names.add(term)
    edges = []
    for t, pres in PRE.items():
        if t not in names:
            sys.exit(f"PRE 中的术语不在术语表里：{t}")
        for p in pres:
            if p not in names:
                sys.exit(f"先修术语不在术语表里：{p}（{t}）")
            edges.append([p, t])
    old = (LG / "data.js").read_text(encoding="utf-8")
    head = old[:old.index("var NODES")]
    head = head.replace(head[head.index("var CATS"):head.index(";", head.index("var CATS")) + 1],
                        "var CATS = " + json.dumps(CATS, ensure_ascii=False) + ";")
    head = head.replace("附录 D", "附录 C")
    body = "var NODES = [\n" + ",\n".join("  " + json.dumps(n, ensure_ascii=False) for n in nodes) + "\n];\n"
    body += "var EDGES = " + json.dumps(edges, ensure_ascii=False) + ";\n"
    (LG / "data.js").write_text(head + body, encoding="utf-8")
    print(f"节点 {len(nodes)} 个，先修关系 {len(edges)} 条")


if __name__ == "__main__":
    main()
